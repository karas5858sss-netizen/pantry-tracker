export type TranslationKey = keyof typeof translations.ru;

/**
 * Detects supported language from Telegram language_code.
 */
export function detectLanguage(telegramLang?: string): SupportedLanguage {
  if (!telegramLang) return 'ru';
  const code = telegramLang.toLowerCase().slice(0, 2);
  if (code === 'es') return 'es';
  if (code === 'en') return 'en';
  return 'ru';
}

/**
 * Retrieves translated string by key with fallback to Russian and optional param substitution.
 */
export function t(lang: SupportedLanguage, key: TranslationKey, params?: Record<string, string | number>): string {
  const dict = (translations[lang] || translations.ru) as Record<string, string>;
  let str: string = dict[key] || (translations.ru as Record<string, string>)[key] || key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return str;
}
